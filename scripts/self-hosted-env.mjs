import { execFileSync } from "node:child_process";
import { existsSync, writeFileSync } from "node:fs";

const composeFile = "docker/docker-compose.yml";
const envPath = ".env.selfhosted.local";
const force = process.argv.includes("--force");

execFileSync(
  "docker",
  ["compose", "-f", composeFile, "up", "-d", "--wait", "backend"],
  { stdio: "inherit" },
);

if (existsSync(envPath) && !force) {
  console.log(`${envPath} already exists`);
  startDashboard();
  process.exit(0);
}

const output = execFileSync(
  "docker",
  ["compose", "-f", composeFile, "exec", "-T", "backend", "./generate_admin_key.sh"],
  { encoding: "utf8" },
);

const lines = output
  .split(/\r?\n/)
  .map((line) => line.trim())
  .filter(Boolean);
const key = lines.findLast((line) => line.includes("|")) ?? lines.at(-1);

if (!key || /\s/.test(key)) {
  console.error("The self-hosted backend did not return an admin key.");
  process.exit(1);
}

writeFileSync(
  envPath,
  [
    "# Generated by scripts/self-hosted-env.mjs. Do not commit.",
    "CONVEX_SELF_HOSTED_URL=http://127.0.0.1:3220",
    `CONVEX_SELF_HOSTED_ADMIN_KEY=${key}`,
    "",
  ].join("\n"),
);

console.log(`Wrote ${envPath}`);
startDashboard();

function startDashboard() {
  execFileSync(
    "docker",
    ["compose", "-f", composeFile, "up", "-d", "dashboard"],
    { stdio: "inherit" },
  );
}
